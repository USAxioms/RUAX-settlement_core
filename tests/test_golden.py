SCENARIO_HEIGHT = 5
SCENARIO_STATE = 'ACTIVE'


def scenario():
    W = lambda n: n * WAD
    e = S.Engine()
    e.post([("D", "SL1", "CASH", W(2000000000)), ("C", "SL1", "EQUITY", W(2000000000))])
    e.post([("D", "SL1", "CASH", W(1350000000)), ("C", "SL1", "SENIOR_DEBT", W(1350000000))])
    e.post([("D", "SL1", "CASH", 1), ("C", "SL1", "SENIOR_DEBT", 1)])
    e.mark_ev(W(2800000000))
    e.audit_unfreeze()
    e.audit_unfreeze([("D", "SL1", "SENIOR_DEBT", W(200000000)), ("C", "SL1", "CASH", W(200000000))])
    return e


class TestGolden(unittest.TestCase):
    def test_constants(self):
        self.assertEqual((hp.LN2, hp.LN10), (LN2, LN10))

    def test_ln(self):
        for x, v in LN:
            self.assertEqual(hp.ln(D(x)), v, x)
        self.assertEqual(hp.ln(hp.P), 0)

    def test_exp(self):
        for x, v in EXP:
            self.assertEqual(hp.exp(D(x)), v, x)
        for w, v in EXP_WAD:
            self.assertEqual(hp.exp(w * hp.K), v, w)
        self.assertEqual(hp.exp(0), hp.P)

    def test_engine_chain_head(self):
        e = scenario()
        self.assertEqual((e.head, e.log_head, e.height, e.state), (SCENARIO_HEAD, SCENARIO_LOG_HEAD, SCENARIO_HEIGHT, SCENARIO_STATE))
        self.assertTrue(S.verify_chain(e))


